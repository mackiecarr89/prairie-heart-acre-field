export function defaultFlags(role: RoleId): Pick<Style, "bold" | "italic" | "underline" | "strike"> {
  return {
    bold: role === "keyword" || role === "control" || role === "heading" || role === "warning" || role === "invalid",
    italic: role === "comment" || role === "doc" || role === "emphasis" || role === "parameter",
    underline: role === "invalid",
    strike: role === "deleted",
  };
}

export function styleFrom(role: RoleId, color: string): Style {
  return { color, ...defaultFlags(role) };
}

export type TextmateRule = {
  id: string;
  name: string;
  role: RoleId;
  scopes: string[];
  flags?: Partial<Pick<Style, "bold" | "italic" | "underline" | "strike">>;
};

function tm(
  id: string,
  name: string,
  role: RoleId,
  scopes: string[],
  flags?: TextmateRule["flags"],
): TextmateRule {
  return { id, name, role, scopes, flags };
}

