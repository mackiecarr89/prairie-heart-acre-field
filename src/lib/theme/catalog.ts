export type SemanticRule = {
  id: string;
  label: string;
  detail: string;
  role: RoleId;
  /** When true, export font style only — do not paint a foreground. */
  styleOnly?: boolean;
  flags?: Partial<Pick<Style, "bold" | "italic" | "underline" | "strike">>;
};

function sem(
  id: string,
  label: string,
  detail: string,
  role: RoleId,
  extra?: Partial<SemanticRule>,
): SemanticRule {
  return { id, label, detail, role, ...extra };
}

